/// 오류 화면에서 1:1 문의로 넘어갈 때 채워 넣을 **초안**을 만든다(P2-11).
///
/// ## 왜 필요한가
///
/// 지금은 AI 가이드가 실패하면 사용자가 할 수 있는 것이 "다시 시도"뿐이고,
/// 문의를 넣더라도 **무엇이 실패했는지가 하나도 실리지 않는다.** 그래서
/// 테스터 피드백이 *"가끔 안 돼요"*에서 멈춘다 — 받는 쪽은 언제 어느
/// 화면에서 어떤 실패였는지 되물어야 하고, 되묻는 사이에 사용자는 답을
/// 잊는다.
///
/// ## 🚨 무엇을 넣지 않는가 — 이 파일의 존재 이유가 여기 있다
///
/// 이 함수가 만든 글은 **문의 본문으로 서버에 저장된다.** 그러므로:
///
/// ```
/// 넣는다     오류 코드 · 발생 시각 · 앱 버전 · 어느 화면이었나
/// 안 넣는다  명함 주인의 이름·회사·전화·이메일 — 제3자 개인정보다
/// 안 넣는다  예외 원문(toString) — 무엇이 실려 오는지 우리가 정하지 못한다
/// ```
///
/// ⚠️ **오류가 난 화면이 특정 인맥의 화면이어도 그 사람을 적지 않는다.**
/// 받는 쪽이 알아야 하는 것은 "어떤 실패였나"이지 "누구에게서 났나"가
/// 아니다. 누구인지가 정말 필요하면 그때 사용자에게 물으면 된다.
///
/// ⚠️ **예외 원문을 넣지 않는 이유**는 그것이 우리 문구가 아니기 때문이다.
/// 서버·플러그인이 만든 문자열이라 내용이 바뀔 수 있고, 입력값이 그대로
/// 되돌아오는 형태이면 개인정보가 섞여 나갈 수 있다. 대신 [code]처럼
/// **우리가 정한 값**만 싣는다.
///
/// ## 📌 채우기만 하고 보내지 않는다
///
/// 이 초안은 문의 작성 화면에 **미리 적혀 있을 뿐**이고, 사용자가 읽고
/// 고쳐서 직접 보낸다. 이 저장소에서 **앱이 만든 문장이 사용자 데이터로
/// 저장되고 AI 요청에까지 실려 나간 일이 두 번** 있었다(태그 기본값
/// `'AI, IT'`, 메모 자동 문구). 같은 모양을 만들지 않으려는 것이다.
library;

/// 문의 제목. 목록에서 한눈에 오류 문의임을 알아보게 짧게 둔다.
String buildErrorReportSubject(String screenLabel) => '[오류] $screenLabel';

/// 문의 본문 초안.
///
/// [code]는 우리가 정한 오류 코드(예: `ai-quota-exceeded`), [codeLabel]은 그
/// 코드를 사람이 읽을 수 있게 옮긴 한 줄이다. **코드만 적으면 안 된다** —
/// 이 글은 사용자가 읽고 보내는 것이라, 영문 코드만 있으면 자기가 무엇을
/// 보내는지 모른 채 보내게 된다. [screenLabel]은 사람이 읽는 화면 이름
/// (예: `AI 대화 가이드`), [occurredAt]은 발생 시각, [appVersion]은
/// `AppVersion.display` — 커밋 해시까지 들어 있어 **어느 빌드인지 특정**된다
/// (이 저장소는 낡은 빌드를 버그로 오인한 적이 있다).
///
/// 마지막 줄은 **비워 두고 사용자가 쓰도록** 안내한다 — 우리가 채운 부분과
/// 사용자가 쓴 부분이 섞이면 받는 쪽이 무엇을 믿어야 할지 알 수 없다.
String buildErrorReportBody({
  required String code,
  required String codeLabel,
  required String screenLabel,
  required DateTime occurredAt,
  required String appVersion,
}) {
  final at = _formatLocal(occurredAt);
  return '아래는 앱이 자동으로 적은 내용입니다. 고치거나 지우셔도 됩니다.\n'
      '\n'
      '· 화면: $screenLabel\n'
      '· 오류 코드: $code ($codeLabel)\n'
      '· 발생 시각: $at\n'
      '· 앱 버전: $appVersion\n'
      '\n'
      '무엇을 하시던 중이었는지 적어 주시면 원인을 찾는 데 큰 도움이 됩니다.\n';
}

/// `2026-09-02 14:05` 형태. 기기의 현지 시각을 그대로 쓴다.
///
/// `intl` 패키지를 쓰지 않는다 — 이 한 줄을 위해 의존성을 늘릴 이유가 없고,
/// 형식이 고정이라 직접 만드는 편이 테스트하기도 쉽다.
String _formatLocal(DateTime at) {
  final t = at.toLocal();
  String two(int v) => v.toString().padLeft(2, '0');
  return '${t.year}-${two(t.month)}-${two(t.day)} ${two(t.hour)}:${two(t.minute)}';
}
