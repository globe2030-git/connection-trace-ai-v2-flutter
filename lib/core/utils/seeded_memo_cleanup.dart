/// 스캔이 자동으로 넣던 문구가 **그대로 남은** 메모인지 판정한다.
///
/// 2026-08-15까지 명함을 스캔하면 메모 칸에
/// `'AI OCR 스캔으로 자동 추출된 명함 텍스트 정보입니다.'`가 무조건 들어갔다.
/// 사용자가 쓰지 않은 문장이 사용자 메모로 저장된 것이라, 태그 기본값
/// `'AI, IT'`(빌드6·7 통합본 E-08, backlog 추가 204)와 같은 유형의 가짜
/// 데이터다. 넣던 코드는 없앴지만(backlog 추가 223) **이미 저장된 명함에는
/// 남아 있다.**
///
/// 게다가 이 문장은 AI 브리핑 요청에 `메모:`로 그대로 실려 나간다 — 아무
/// 정보도 없는 문장에 토큰을 쓰고, AI는 그것을 그 사람에 대한 맥락으로 읽는다.
/// 지우면 그 오염도 함께 사라진다.
///
/// ## 메모를 통째로 지우지 않고, 그 **줄만** 걷어낸다
///
/// ⚠️ 판정이 틀리면 **사용자가 직접 쓴 메모를 지운다.** 처음에는 그래서 메모가
/// **그 문장 하나뿐**일 때만 대상으로 삼았다([isSeededScanMemo]).
///
/// 그런데 실기기 확인에서 그 규칙이 놓치는 모양이 나왔다(2026-08-15):
///
/// ```
/// [이전 정보 · 2026-08-14] E Mail / 대표 IG: … / 010-… / …@naver.com
/// AI OCR 스캔으로 자동 추출된 명함 텍스트 정보입니다.
/// ```
///
/// 앞줄은 사용자가 명함 업데이트 때 "기록으로 남기기"를 골라 **앱이 만든**
/// 블록이다. 사람이 쓴 글이 아닌데도 "덧붙였으니 손대지 않는다"에 걸려
/// 남았고, 문장은 그대로 AI 브리핑에 실려 나갔다.
///
/// 그래서 판정을 "메모 전체가 그 문장인가"에서 **"그 문장만 있는 줄이 있는가"**
/// 로 넓히되, 지우는 범위는 **그 줄 하나**로 좁힌다. 메모를 비우는 것이 아니라
/// 그 줄만 빼므로, 같은 메모에 사용자가 쓴 내용이 있어도 그대로 남는다.
///
/// 여전히 건드리지 않는 것: 문장이 **다른 글과 한 줄에 섞여 있는** 경우
/// (`'메모: AI OCR …'`). 그건 사용자가 그 줄을 직접 편집했다는 뜻이고,
/// substring을 도려내면 `'메모:'` 같은 조각이 남는다.
///
/// 태그 정리([isSeededDefaultTagSet])와 같은 판단이다 — 잘못 채워진 값을
/// 지우려다 맞는 값을 지우는 쪽이 더 나쁘다.
library;

/// 스캔이 넣던 문구. 앱에서는 더 이상 쓰지 않지만, **이미 저장된 값을 알아보려면
/// 원문이 필요**하다. 지우는 쪽에만 남겨 둔다.
const _seededMemo = 'AI OCR 스캔으로 자동 추출된 명함 텍스트 정보입니다.';

/// [memo]가 스캔이 넣은 문구 그대로인가.
///
/// 앞뒤 공백은 무시한다 — 저장·복원을 거치며 줄바꿈이 붙는 경우가 있다.
///
/// 정리 동작은 이제 [memoHasSeededScanLine]/[withoutSeededScanLine]을 쓴다.
/// 이 함수는 "메모 전체가 그 문장"인 좁은 경우를 가리키는 이름으로 남겨 둔다.
bool isSeededScanMemo(String? memo) {
  if (memo == null) return false;
  return memo.trim() == _seededMemo;
}

/// [memo] 안에 **그 문장만 있는 줄**이 있는가 — 정리 대상 판정.
///
/// 줄 단위로 본다. 다른 글과 한 줄에 섞인 경우는 대상이 아니다(위 주석 참고).
bool memoHasSeededScanLine(String? memo) {
  if (memo == null) return false;
  return memo.split('\n').any((line) => line.trim() == _seededMemo);
}

/// [memo]에서 그 문장만 있는 줄을 걷어낸 결과.
///
/// 줄을 뺀 뒤 앞뒤 공백을 정리한다. 남는 것이 없으면 빈 문자열을 돌려준다 —
/// 호출부가 그대로 저장하면 메모가 비워진다(옛 [isSeededScanMemo] 경우와 같은
/// 결과).
String withoutSeededScanLine(String memo) {
  final kept = memo
      .split('\n')
      .where((line) => line.trim() != _seededMemo)
      .join('\n');
  return kept.trim();
}
