/// 스캔이 자동으로 넣던 문구가 **그대로 남은** 메모인지 판정한다.
///
/// 2026-08-15까지 명함을 스캔하면 메모 칸에
/// `'AI OCR 스캔으로 자동 추출된 명함 텍스트 정보입니다.'`가 무조건 들어갔다.
/// 사용자가 쓰지 않은 문장이 사용자 메모로 저장된 것이라, 태그 기본값
/// `'AI, IT'`(빌드6·7 통합본 E-08, backlog 추가 204)와 같은 유형의 가짜
/// 데이터다. 넣던 코드는 없앴지만(backlog 추가 223) **이미 저장된 명함에는
/// 남아 있다.**
///
/// 게다가 이 문장은 AI 브리핑 요청에 `메모:`로 그대로 실려 나간다 — 아무
/// 정보도 없는 문장에 토큰을 쓰고, AI는 그것을 그 사람에 대한 맥락으로 읽는다.
/// 지우면 그 오염도 함께 사라진다.
///
/// ## 대상을 좁게 잡는다
///
/// ⚠️ 이 판정이 틀리면 **사용자가 직접 쓴 메모를 지운다.** 그래서 메모가
/// **그 문장 하나뿐**일 때만 참이다. 사용자가 뒤에 무언가 덧붙였다면 그 칸을
/// 의식하고 손댔다는 뜻이므로 건드리지 않는다.
///
/// 태그 정리([isSeededDefaultTagSet])와 같은 판단이다 — 잘못 채워진 값을
/// 지우려다 맞는 값을 지우는 쪽이 더 나쁘다.
library;

/// 스캔이 넣던 문구. 앱에서는 더 이상 쓰지 않지만, **이미 저장된 값을 알아보려면
/// 원문이 필요**하다. 지우는 쪽에만 남겨 둔다.
const _seededMemo = 'AI OCR 스캔으로 자동 추출된 명함 텍스트 정보입니다.';

/// [memo]가 스캔이 넣은 문구 그대로인가.
///
/// 앞뒤 공백은 무시한다 — 저장·복원을 거치며 줄바꿈이 붙는 경우가 있다.
/// 그 밖의 차이(뒤에 사용자가 덧붙인 글, 문장 일부 수정)는 **모두 사용자가
/// 손댄 것으로 본다.**
bool isSeededScanMemo(String? memo) {
  if (memo == null) return false;
  return memo.trim() == _seededMemo;
}
