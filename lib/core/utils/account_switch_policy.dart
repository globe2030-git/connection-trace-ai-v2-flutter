/// 계정 전환 뒤 **서버로 다시 올려도 되는가**를 정하는 규칙.
///
/// ## ⚠️ 무엇을 막는 규칙인가
///
/// 로그인 직후 도는 일회성 마이그레이션(`_stripGeoFromServerBackupsOnce`)은
/// **로컬 명함 전체를 지금 계정의 서버 문서로 올린다.** 계정을 바꾼 직후라면
/// 그 명함은 **이전 계정이 수집한 것**이다.
///
/// ```
/// 2026-08-21 실측 — 구글 → 카카오 → 네이버로 연속 전환한 결과
/// 같은 명함 95건이 세 계정 서버에 전부 존재하게 됐다
/// ```
///
/// ⚠️ 명함은 **제3자(명함 주인)의 개인정보**다. 두 계정이 다른 사람이면
/// 근거 없는 제3자 제공이 된다.
///
/// ## 규칙
///
/// ```
/// 계정 전환이 아니다        → 허용. 올려도 자기 데이터다
/// 전환 + "교체"를 골랐다     → 허용. 이미 이 계정 데이터로 갈아 끼운 뒤다
/// 전환 + "유지"를 골랐다     → ⚠️ 금지. 이전 계정 명함이 올라간다
/// 이전 계정을 알 수 없다     → ⚠️ 금지. 전환인지 아닌지 모른다
/// ```
///
/// 📌 마지막 줄이 중요하다. 저장소에서 마지막 uid를 못 읽으면 **전환 여부를
/// 판단할 수 없다.** 모르는 채로 올리면 남의 명함을 올릴 수 있으므로 막는다
/// (모를 때는 안전한 쪽으로 — 다음 로그인에 다시 기회가 온다).
library;

/// 지금 서버로 일회성 마이그레이션을 돌려도 되는지.
///
/// - [lastUidKnown] : 마지막으로 로그인했던 계정을 읽어냈는가
/// - [isAccountSwitch] : 그 계정과 지금 계정이 다른가(로컬에 데이터가 있는 상태)
/// - [replaced] : 전환 화면에서 "현재 계정 데이터로 교체"를 골랐는가
bool mayMigrateToServer({
  required bool lastUidKnown,
  required bool isAccountSwitch,
  required bool replaced,
}) {
  if (!lastUidKnown) return false;
  if (!isAccountSwitch) return true;
  return replaced;
}
