/// 스캔한 명함의 몇 번째 면인지를 사람이 읽는 라벨로 바꾼다(추가 426).
///
/// 편집 화면의 앞/뒤 세그먼트와 전체화면 뷰어의 배지("앞면 1/2")가 이 라벨을
/// 그대로 쓴다. 명함은 보통 앞뒤 두 면이지만(추가 293), 접이식·부록면이 있는
/// 명함도 있어 세 번째 면부터는 "N번째 면"으로 순번만 붙인다 — 세 장 이상을
/// 막지 않는 기존 정책과 같은 결이다.
String cardFaceLabel(int index) {
  switch (index) {
    case 0:
      return '앞면';
    case 1:
      return '뒷면';
    default:
      return '${index + 1}번째 면';
  }
}
