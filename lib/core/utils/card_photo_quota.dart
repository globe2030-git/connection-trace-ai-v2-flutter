/// 명함 사진 **서버 백업 장수 한도** 계산(2026-08-16).
///
/// ## 왜 한도가 있나
///
/// **충전형은 "AI를 쓸 때" 받는데, 사진 저장은 "안 써도 계속 나가는" 비용이다.**
/// 무료 이용자가 AI를 한 번도 쓰지 않아도 매달 저장 요금이 나가고, **회수
/// 경로가 없다.** 한도는 매출 장치가 아니라 **천장 장치**다 — "최악이어도
/// 여기까지"를 말할 수 있게 한다.
///
/// 근거·계산: `docs/planning/card-photo-storage-cost-spec-2026-08-16.md`
///
/// ## ⚠️ 한도는 상수가 아니다 — 사용자마다 다르다
///
/// [kCardPhotoQuota]는 **기본값일 뿐**이고, 진짜 값은 서버의
/// `users/{uid}.cardPhotoQuota`다.
///
/// - **컴파일 상수로 박으면 올릴 때마다 앱을 새로 배포**해야 한다. 한도는
///   *"낮게 시작해 필요하면 올린다"*는 전제 위에 정해졌으므로 올릴 일이 온다
/// - ⚠️ 그 필드는 **`firestore.rules`의 `clientWritableUserFields()`에 넣지
///   않는다.** 넣으면 **이용자가 자기 한도를 늘려** 한도가 무의미해진다
///   (AI 잔여 회차와 같은 원칙)
///
/// ## 제한하는 것은 **서버 백업**뿐이다
///
/// 명함 등록·기기 저장·검색·AI는 **전부 무제한**이다. 한도를 넘어도
/// **명함은 정상 저장되고 사진도 기기에는 남는다.** 서버 업로드만 멈춘다.
///
/// ⚠️ **이미 올라간 것은 건드리지 않는다.** 밀어내기(오래된 것부터 삭제)를
/// 하지 않는 이유는 UX가 아니라 **법무**다 — 개인정보처리방침이 적은 사진
/// 파기 사유는 **"명함 삭제 시"와 "회원 탈퇴 시" 둘뿐**이고, *"한도를 넘어
/// 회사가 지운다"*는 근거가 없다.
library;

/// 기본 한도. **무료·충전 구분 없이 하나다**(2026-08-26 사용자 확정).
///
/// ## 왜 구분을 없앴나
///
/// 종전에는 **무료 200 / 충전 2,000** 이었다(2026-08-16). 그런데 그 값은
/// **월 구독형을 전제로 정해진 것**이고, 그 뒤 과금이 **충전형**으로 바뀌면서
/// 앞뒤가 안 맞게 됐다.
///
/// ```
/// 월 구독   구독 중이면 2,000장, 끊으면 200장   ← 자연스럽다
/// 충전형    한 번 충전하고 다 쓰면?             ← 여기서 막힌다
/// ```
///
/// 🚨 한도를 200으로 되돌려도 **이미 올라간 것을 지울 근거가 없다.**
/// 개인정보처리방침이 적은 사진 파기 사유는 *"명함 삭제 시"* 와
/// *"회원 탈퇴 시"* 둘뿐이다. 즉 **₩2,000 한 번 받고 그 사람의 저장 비용을
/// 영원히 지는** 구조였다.
///
/// 📌 그리고 **충전 구분은 애초에 구현된 적이 없다.** 옛 상수(충전용 2,000)를
/// 쓰는 코드가 **0건**이었고, 서버에 `users/{uid}.cardPhotoQuota` 를 써 주는
/// 함수도 없었다. **없애는 것이 아니라 안 만드는 것**이다.
///
/// ## 왜 하필 2,000인가
///
/// **비용이 아니라 이탈로 정했다.** 한도를 올려도 **오늘 요금은 1원도 안
/// 는다** — 요금은 실제로 쌓인 장수로 정해지고, 한도는 *"최악이 어디서
/// 멈추나"* 만 정한다.
///
/// ⭐ 결정적인 것은 **명함이 많은 사람이 곧 AI를 많이 쓸 사람**이라는 점이다
/// (2026-08-26 계산).
///
/// ```
/// 명함 2,000장 보유자의 사진 연비용   약 ₩261 (보관 12개월 + 연 1회 전량 복원)
/// 같은 사람의 AI 잠재 마진             약 ₩32,136 (명함당 1회 기준)
///                                     → 123배
/// ```
///
/// 🚨 **사진 한도로 조인다는 것은 가장 돈 되는 이용자를 골라 조인다는
/// 뜻이다.** 그것도 **기기를 바꾸는 순간**에.
///
/// ⚠️ 그래도 무제한으로 두지 않는 이유는 그대로다 — **상한이 있어야 최악을
/// 계산할 수 있다.** 2,000장은 월 3장이면 55년이라 사실상 아무도 안 닿는다.
/// 80% 경고선(1,600장)도 44년이라 **경고 자체가 뜰 일이 거의 없다.**
///
/// ⚠️ **되돌릴 수 없는 방향이다.** 올리기는 언제든 되고 내리기는 못 한다
/// (초과분을 지울 근거가 방침에 없다). 지금은 서버에 사진이 0장이라
/// **정하는 것이 공짜지만, 켠 뒤에는 못 바꾼다.**
///
/// ⚠️ 이 결정의 근거인 *"명함이 많으면 AI를 쓴다"* 는 **아직 안 잰 가정**이다.
/// 테스터 계정으로 「명함 수 ↔ AI 사용 횟수」 상관을 재기로 했다(추가 512).
const int kCardPhotoQuota = 2000;

/// 미리 알리는 지점. 한도의 **80%**.
///
/// ⚠️ **걸린 뒤에 알면 늦다.** 사진 백업은 보험이라, 한도에 걸린 것을 **기기를
/// 바꾼 뒤에 알게 되면** 그때는 충전이 아니라 이탈이다.
const double kCardPhotoQuotaWarnRatio = 0.8;

/// 서버 값이 없거나 이상하면 기본값을 쓴다.
///
/// 0이나 음수는 **"백업을 끈다"는 뜻이 아니라 잘못 들어간 값**으로 본다 —
/// 그런 값 때문에 백업이 조용히 멈추면 사용자는 이유를 알 수 없다.
int resolveQuota(int? serverValue) {
  if (serverValue == null || serverValue <= 0) return kCardPhotoQuota;
  return serverValue;
}

/// 이 장수에서 **더 올릴 수 있나**.
bool canUpload(int syncedCount, int quota) => syncedCount < quota;

/// 미리 알려야 하는 구간인가(80% 이상, 아직 한도 안).
///
/// 한도에 닿은 뒤에는 [canUpload]가 false가 되므로 여기서는 false다 —
/// **"곧 찹니다"와 "찼습니다"는 다른 안내**다.
bool isNearQuota(int syncedCount, int quota) {
  if (!canUpload(syncedCount, quota)) return false;
  return syncedCount >= warnThreshold(quota);
}

/// 미리 알리기 시작하는 장수. 기본 한도 2,000장이면 **1,600장**.
int warnThreshold(int quota) => (quota * kCardPhotoQuotaWarnRatio).floor();

/// 남은 장수. 이미 넘었으면 0.
int remainingSlots(int syncedCount, int quota) {
  final left = quota - syncedCount;
  return left < 0 ? 0 : left;
}
