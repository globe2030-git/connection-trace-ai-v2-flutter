import 'dart:io';

import 'package:flutter/painting.dart';

/// **같은 경로에 이미지를 덮어썼을 때** Flutter의 이미지 캐시를 비운다.
///
/// 왜 필요한가: `FileImage`의 캐시 키는 **파일 경로**다. 파일 내용이 바뀌어도
/// 경로가 같으면 캐시에 있던 **옛 픽셀을 그대로** 돌려준다. `setState`로 다시
/// 그려도 소용이 없다 — 위젯은 다시 만들어지지만 같은 키로 같은 캐시를 조회하기
/// 때문이다.
///
/// 실제로 겪은 것(빌드7 · Galaxy S24+, 통합본 E-07): 본인 명함 등록 중 갤러리에서
/// 사진을 골라도 **미리보기가 안 바뀌었다.** 저장은 정상이라 앱을 껐다 켜면
/// 새 사진이 보였다 — 앱 재시작 때 이미지 캐시가 비워지기 때문이다.
///
/// 파일명에 타임스탬프를 붙여 매번 다른 경로로 저장하는 방법도 있지만, 그러면
/// **옛 파일이 쌓이고** 프로필에 저장된 경로도 매번 바뀌어 지우는 책임이 는다.
/// 고정 파일명을 유지하고 **캐시만 비우는 쪽**이 원인에 정확히 대응한다.
///
/// ⚠️ 파일을 쓴 **직후, 화면을 다시 그리기 전에** 부른다.
Future<void> evictImageFileCache(String path) async {
  await FileImage(File(path)).evict();
}
