/// 로그인 이메일을 화면에 **가려서** 보여준다.
///
/// ## 왜 가리나
///
/// 설정 화면의 계정 줄은 *"지금 어느 계정으로 들어와 있는지"* 를 알려 주는
/// 자리다. 이 앱은 로그인 수단이 넷(구글·애플·카카오·네이버)이고 **제공자가
/// 다르면 서로 다른 계정**이라, 이 줄이 없으면 *"내 명함이 다 사라졌어요"* 의
/// 흔한 원인(다른 수단으로 로그인)을 아무도 못 가린다.
///
/// ⚠️ 그런데 **늘 펼쳐 둘 이유는 없다.** 화면을 남에게 보여주거나 캡처를
/// 공유하면 그대로 나간다(2026-08-21 실제로 캡처에 찍혔다). 공용 기기·시연·
/// 영업 현장도 마찬가지다.
///
/// 📌 본인 정보이므로 제3자 개인정보 원칙과는 다른 문제다. 법적 의무가 아니라
/// **필요 이상으로 계속 떠 있지 않게 하는 것**이 목적이다.
///
/// ## 무엇을 남기나
///
/// ```
/// globe@creamhouse.net  →  gl****@creamhouse.net
/// ```
///
/// ⚠️ **도메인은 남긴다.** 회사 계정인지 개인 계정인지가 계정을 가리는
/// 실마리라, 그것까지 가리면 원래 목적이 죽는다.
///
/// ⚠️ **별표 개수는 실제 길이와 무관하게 고정이다.** 길이에 맞추면 아이디가
/// 몇 자인지가 드러난다 — 가리는 시늉만 하는 셈이다.
library;

/// 가림에 쓰는 별표. 길이를 드러내지 않으려고 고정 개수를 쓴다.
const String _mask = '****';

/// 앞에 남길 글자 수.
const int _keep = 2;

/// [email] 을 가린 형태로 돌려준다.
///
/// - `@` 가 없으면 이메일이 아니므로 **앞 [_keep] 자만 남기고** 가린다.
///   (애플 릴레이나 제공자가 이상한 값을 줄 때를 대비한다 — 모르는 값을
///   그대로 펼쳐 두는 것보다 가리는 쪽이 안전하다.)
/// - 아이디가 짧으면 남기는 글자를 줄인다. **한 글자짜리도 그 한 글자는
///   남긴다** — 전부 가리면 계정을 가릴 단서가 사라진다.
/// - 비어 있으면 그대로 돌려준다.
String maskEmail(String email) {
  final value = email.trim();
  if (value.isEmpty) return value;

  final at = value.lastIndexOf('@');
  if (at <= 0) {
    // @ 가 없거나 맨 앞에 있다 — 도메인을 가려낼 수 없다.
    final head = value.substring(0, value.length < _keep ? value.length : _keep);
    return '$head$_mask';
  }

  final local = value.substring(0, at);
  final domain = value.substring(at); // '@' 포함
  final keep = local.length < _keep ? local.length : _keep;
  return '${local.substring(0, keep)}$_mask$domain';
}
