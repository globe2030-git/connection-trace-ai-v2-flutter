import 'package:flutter/foundation.dart';
import 'package:webview_flutter/webview_flutter.dart';

/// 소셜 로그인 웹뷰가 기기에 남긴 **로그인 흔적(쿠키)** 을 지운다.
///
/// ## ⚠️ 왜 필요한가 — 남의 계정으로 들어가진다
///
/// 카카오·네이버 로그인은 웹뷰 안에서 이뤄지고, 제공자는 웹뷰에 **자기
/// 세션 쿠키**를 남긴다. 우리 앱에서 로그아웃해도 그 쿠키는 그대로다.
///
/// ```
/// 1. 갑이 카카오로 로그인한다        → 웹뷰에 갑의 카카오 세션 쿠키가 남는다
/// 2. 갑이 앱에서 로그아웃한다        → 우리 세션만 지워진다
/// 3. 을이 '카카오로 계속하기'를 누른다 → 아이디를 묻지 않고 갑으로 통과한다
/// 4. 을이 갑의 명함(제3자 개인정보)을 본다
/// ```
///
/// ⚠️ **4번이 이 앱에서 특히 무겁다.** 이 앱이 담고 있는 것은 이용자 본인의
/// 정보가 아니라 **명함 주인들의 개인정보**다. 계정 하나가 새면 그 사람의
/// 인맥 전체가 샌다.
///
/// 📌 기기를 함께 쓰는 상황은 드물지 않다 — 업무용 공용 태블릿, 매장 시연기,
/// 중고로 넘긴 기기. 계정 삭제 뒤에도 남아 있으면 "탈퇴했는데 다시 눌렀더니
/// 로그인되더라"가 된다.
///
/// ## 구글·애플과 다른 점
///
/// 구글·애플은 네이티브 SDK가 자기 세션을 스스로 정리한다(`GoogleSignIn
/// .signOut()`). 웹뷰로 붙인 카카오·네이버에는 그런 것이 없으므로 **우리가
/// 지워야 한다.**
///
/// ## 실패해도 로그아웃은 계속한다
///
/// 쿠키를 못 지웠다고 로그아웃을 멈추면, 이용자는 로그아웃 자체를 못 한다.
/// 더 나쁜 결과다. 실패는 로그로만 남긴다.
typedef ClearSocialWebSession = Future<void> Function();

Future<void> clearSocialWebSession() async {
  try {
    await WebViewCookieManager().clearCookies();
  } catch (e) {
    // 플랫폼 채널이 없는 환경(테스트 등)에서는 그냥 넘어간다.
    debugPrint('[SocialWebSession] 쿠키 정리 실패: $e');
  }
}
