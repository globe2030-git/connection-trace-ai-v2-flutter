def H(text, level=1):
    p = d.add_heading(text, level=level)
    for r in p.runs:
        r.font.name = 'Apple SD Gothic Neo'
        r.font.color.rgb = RGBColor(0x1a, 0x1a, 0x1a)
    return p


def P(text, bold=False, size=10.5, space_after=6):
    p = d.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    r = p.add_run(text)
    r.bold = bold
    r.font.size = Pt(size)
    r.font.name = 'Apple SD Gothic Neo'
    return p


def BUL(text, level=0):
    p = d.add_paragraph(text, style='List Bullet')
    p.paragraph_format.left_indent = Cm(0.6 + 0.5 * level)
    p.paragraph_format.space_after = Pt(3)
    for r in p.runs:
        r.font.name = 'Apple SD Gothic Neo'
        r.font.size = Pt(10.5)
    return p


def TABLE(headers, rows, widths=None):
    t = d.add_table(rows=1, cols=len(headers))
    t.style = 'Light Grid Accent 1'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ''
        r = c.paragraphs[0].add_run(h)
        r.bold = True
        r.font.size = Pt(10)
        r.font.name = 'Apple SD Gothic Neo'
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            r = cells[i].paragraphs[0].add_run(str(v))
            r.font.size = Pt(10)
            r.font.name = 'Apple SD Gothic Neo'
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    d.add_paragraph().paragraph_format.space_after = Pt(4)
    return t


