// **직함의 나머지 반쪽을 버리던 것**을 되돌린 규칙(2026-08-30).
//
// ## 무엇이 잘못됐나
//
// 기기 채점에서 직함이 틀린 셋이 전부 같은 모양이었다.
//
// ```
// 대표이사 | CEO         →  「대표이사」        CEO 를 잃었다
// 이사장/ President CEO  →  「이사장」          영문 표기를 잃었다
// 대표/공인중개사         →  「대표」            자격을 잃었다
// ```
//
// 출처는 #684(`07dfe83`)로 특정됐다. 그 PR 은 52장 실측으로 **직함 칸에서
// 걷어낼 것을 걷어냈다** — 틀린 변경이 아니었다. 다만 **그물이 「직함의 영문
// 반쪽」과 「자격 표기」까지 함께 걸었다.**
//
// ## 무엇을 고쳤나 — 한 줄이다
//
// **부서를 못 얻었으면 가르지 않은 것과 같아야 한다.** 예전에는 `head` 만
// 남기고 나머지를 그냥 버렸다.
//
// > 가르기의 목적은 **부서를 건져 내는 것**이지 **직함을 줄이는 것**이 아니다.
//
// ## 🚨 되살아날 위험을 재고 넣었다
//
// 다른 세션이 경고했다 — *"`대표 ceo / HEE-JUNG JOO` 처럼 **사람 이름**이
// 붙어 오는 줄이 통째로 돌아온다"*. 맞는 걱정이라 **찾아서 확인했다.**
//
// ```
// 그 명함은 card_132 다. 기기 원문 96장 채점에서 되살아난 장 0.
// ```
//
// 그런 줄은 이 경로까지 오지 않는다(전화·이메일이 섞여 직함 줄로 안 잡힌다).
// ⚠️ **되살아나면 「버릴 것을 가리는 규칙」을 따로 만들어야지, 이 규칙을
// 되돌리면 회귀 셋이 다시 난다.**
//
// ## 잰 것 — 기기 원문 96장 · 사람이 전사한 정답지
//
// ```
// 직함   64% → 66%     부서 73% → 75%     전체 82%
// ```
import 'package:connection_trace_ai_flutter/core/services/ocr_scanner_service.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  OcrScanResult parse(List<String> lines) =>
      OcrScannerService.parseLinesForTesting(lines);

  group('직함의 나머지 반쪽을 지킨다 — 회귀 셋', () {
    test('영문 표기를 버리지 않는다 — card_02', () {
      final r = parse(['박병건 Andy Park', '대표이사 | CEO', '(주) TG360', '010-1234-5678']);
      expect(r.title, '대표이사 | CEO');
    });

    test('영문이 두 낱말이어도 지킨다 — card_19', () {
      final r = parse(['홍길동', '이사장/ President CEO', '(주)한빛정보기술', '010-1234-5678']);
      expect(r.title, contains('President CEO'));
    });

    test('자격 표기를 버리지 않는다 — card_133', () {
      // `공인중개사`는 자격이자 직함이다. 부서가 아니다.
      final r = parse(['홍봉표', '대표/공인중개사', '아이클래스 부동산', '010-1234-5678']);
      expect(r.title, '대표/공인중개사');
    });
  });

  group('⭐ 부서를 얻으면 그때는 가른다 — 목적이 바뀐 게 아니다', () {
    test('영문 부서는 갈라낸다', () {
      final r = parse(['이시영', '부사장 / R&D Center', '주식회사 알로이스', '010-1234-5678']);
      expect(r.title, '부사장');
      expect(r.department, 'R&D Center');
    });

    test('접미사 없이 업무 이름으로 끝나는 부서도 갈라낸다', () {
      // `MICE마케팅`은 부서다 — 이것을 못 잡아 직함에 통째로 남았었다.
      final r = parse([
        '서울컨벤션뷰로',
        'MICE마케팅 | 주임',
        '김효은',
        '서울관광재단 04551, 서울특별시 중구 삼일대로 340 8층',
      ]);
      expect(r.title, '주임');
      expect(r.department, '서울컨벤션뷰로 MICE마케팅');
    });

    test('한글 부서도 그대로 — 회귀 확인', () {
      final r = parse(['홍길동', '디지털 커뮤니케이션 파트 / 책임', '(주)한빛정보기술']);
      expect(r.title, '책임');
      expect(r.department, contains('디지털'));
    });
  });

  group('🚨 가르면 안 되는 것 — 이 조건들은 그대로다', () {
    test('한글 직함이 둘이면 안 가른다 — 직급과 직책', () {
      final r = parse(['홍길동', '이사|본부장', '(주)한빛정보기술', '010-1234-5678']);
      expect(r.title, contains('이사'));
      expect(r.title, contains('본부장'));
    });
  });
}
