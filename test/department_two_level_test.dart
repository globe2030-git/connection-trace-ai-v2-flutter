// **두 단계로 인쇄된 부서**를 통째로 잡는 규칙(2026-08-30).
//
// ## 왜
//
// 어제 정답지를 실물로 고치고 나니 부서가 **58%**(일치 35·틀림 5·미검출 20)
// 였고, **틀린 5건이 전부 한 모양**이었다 — 회사의 조직 계층을 위에서 아래로
// 나란히 찍었는데 **아래 한 단계만** 집었다.
//
// ```
// 대리 / 구로지점 / 제1영업본부   →  부서 「제1영업본부」   ← 구로지점을 잃었다
// 팀장 서울사업팀 서울동부지사     →  부서 「서울사업팀」     ← 지사를 잃었다
// 서울컨벤션뷰로                  →  부서 「MICE지원팀」     ← 윗줄을 통째로 잃었다
// MICE지원팀 | 주임
// ```
//
// 📌 **한 조각만 남기면 어느 부서인지 알 수 없어진다.** 「MICE지원팀」은 이
// 재단에 여럿 있고, 「제1영업본부」는 지점이 빠지면 다른 사람 것이 된다.
//
// ## 잰 것 — 기기 원문 96장 · 사람이 전사한 정답지
//
// ```
// 부서   58% → 73%     일치 35 → 44 · 틀림 5 → 5 · 미검출 20 → 11
// 직함   63% → 64%     회사·이름 변동 없음
// ```
//
// 🚨 **이 자는 기기 줄이다**(맥 Vision 아님). 어제 아홉 건을 맥으로만 재고
// 쌓았다가 기기에서 10분 만에 결함 셋이 나왔다 — 그래서 기기 원문으로 잰다.
import 'package:connection_trace_ai_flutter/core/services/ocr_scanner_service.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  OcrScanResult parse(List<String> lines) =>
      OcrScannerService.parseLinesForTesting(lines);

  group('한 줄 안의 계층 — 조각을 다 잇는다', () {
    test('칸막이로 나뉜 두 단계를 다 가져온다', () {
      final r = parse([
        '윤설미',
        '대리 / 구로지점 / 제1영업본부',
        '롯데렌탈주식회사',
        '010-1234-5678',
      ]);
      expect(r.title, '대리');
      expect(r.department, '구로지점 / 제1영업본부');
    });

    test('⚠️ 인쇄된 칸막이를 살린다 — 공백으로 바꾸지 않는다', () {
      // 명함에 `/` 로 찍혀 있으면 그것까지가 그 사람이 받은 표기다.
      final r = parse(['윤설미', '대리 / 구로지점 / 제1영업본부', '(주)한빛']);
      expect(r.department, contains('/'));
    });

    test('상위 조직이 뒤에 오는 명함도 잇는다', () {
      final r = parse(['조남국', '팀장 서울사업팀 서울동부지사', '에스원', '010-1234-5678']);
      expect(r.title, '팀장');
      expect(r.department, '서울사업팀 서울동부지사');
    });

    test('⚠️ 뒤쪽은 조직 꼬리가 있을 때만 잇는다 — 이름·회사를 삼키지 않는다', () {
      final r = parse(['홍길동', '팀장 서울사업팀 에스원', '010-1234-5678']);
      expect(r.department, '서울사업팀');
    });
  });

  group('윗줄에 따로 찍힌 상위 조직', () {
    test('바로 윗줄이 조직이면 부서에 잇는다', () {
      final r = parse([
        '서울컨벤션뷰로',
        'MICE지원팀 | 주임',
        '이현아',
        '서울관광재단 04551, 서울특별시 종로구 청계천로 340, 8층',
      ]);
      expect(r.title, '주임');
      expect(r.department, '서울컨벤션뷰로 MICE지원팀');
      // ⚠️ 회사(`서울관광재단`)를 부서에 섞지 않는다 — 그것만 확인한다.
      //    최소 줄만 준 검사라 회사 칸 자체는 이 검사의 관심이 아니다.
      expect(r.department, isNot(contains('관광재단')));
    });

    test('윗줄 끝에 로고가 붙어 와도 앞머리를 본다', () {
      // 실측: `서울컨벤션뷰로 PLUS SEOUL` 로 로고가 같은 줄에 읽혔다.
      final r = parse([
        '서울컨벤션뷰로 PLUS SEOUL',
        'MICE지원팀 | 대리',
        '김다미',
        '서울관광재단 03190, 서울특별시 종로구 청계천로 85',
      ]);
      expect(r.department, '서울컨벤션뷰로 MICE지원팀');
    });

    test('🚨 회사로 고른 줄은 절대 안 붙인다', () {
      // `서울관광재단`이 회사고 `서울컨벤션뷰로`는 그 안의 본부다.
      // 둘을 섞으면 회사를 잃는다.
      final r = parse(['(주)한빛정보기술', '영업팀 | 대리', '홍길동', '010-1234-5678']);
      expect(r.department, '영업팀');
      expect(r.company, contains('한빛'));
    });
  });

  group('단독으로 찍힌 부서 — 넓힌 조건들', () {
    test('계층을 다 적은 긴 부서도 잡는다 (25자)', () {
      // 20자에서 잘리고 있었다.
      final r = parse([
        'DX사업본부 공공시스템부문 공공시스템2팀',
        '수석 정현규',
        '(주)에이치씨엔씨',
        '010-1234-5678',
      ]);
      expect(r.department, 'DX사업본부 공공시스템부문 공공시스템2팀');
    });

    test('칸막이로 이어 적은 부서를 잇는다', () {
      final r = parse([
        'iTEASY',
        '매니지드운영본부 | 매니지드운영팀',
        '조종환 팀장',
        '(주)아이티이지',
      ]);
      expect(r.department, '매니지드운영본부 매니지드운영팀');
    });

    test('⚠️ 한쪽이라도 조직 모양이 아니면 예전처럼 건너뛴다', () {
      // `A | B` 가 **회사와 후원사**인 경우를 막던 조건이다.
      final r = parse([
        'FC서울프로축구단 | GS칼텍스서울kixx배구단',
        'GS 스포츠',
        '홍길동',
        '010-1234-5678',
      ]);
      expect(r.department, isEmpty);
    });

    test('`평가단`·`사업단`은 부서다 — 다만 `재단`은 회사다', () {
      final r = parse([
        '이노비즈협회(중소기업기술혁신협회)',
        '전문위원',
        '기술평가부문 | 기술인증평가단',
        '조재경',
      ]);
      expect(r.department, '기술평가부문 기술인증평가단');

      final r2 = parse(['서울관광재단', '주임', '홍길동', '010-1234-5678']);
      expect(r2.department, isEmpty);
    });

    test('⬜ 아직 못 잡는 자리 — `기업부설연구소`가 **회사 칸**으로 간다', () {
      // 실측(`card_28`·`102`)에서 미검출로 남은 둘이다. 원인은 부서 쪽이
      // 아니라 **회사 고르기**다 — 접미사 없는 `기업부설연구소`가
      // `(주)그린아이티코리아`보다 먼저 회사로 잡힌다.
      //
      // 📌 이 검사는 「이래야 한다」가 아니라 **「지금 이렇다」**를 적은 것이다.
      //    회사 고르기를 고치면 이 기대가 먼저 깨지고, 그게 신호다.
      final r = parse([
        '기업부설연구소',
        '김효성 연구소장',
        '(주)그린아이티코리아',
        '010-1234-5678',
      ]);
      expect(r.department, isEmpty);
      expect(r.company, '기업부설연구소');
    });
  });

  group('영문 부서', () {
    test('`직함 / 영문조직`을 가른다', () {
      final r = parse(['이시영', '부사장 / R&D Center', '주식회사 알로이스', '010-1234-5678']);
      expect(r.title, '부사장');
      expect(r.department, 'R&D Center');
    });

    test('영문 명함은 마침표를 칸막이로 쓴다', () {
      final r = parse(['안민식', 'BX Center. Business Manager', '(주)한빛', '010-1234-5678']);
      expect(r.department, 'BX Center');
      expect(r.title, contains('Business Manager'));
    });

    test('⚠️ 조직 꼬리 뒤의 마침표만 가른다 — 약어를 쪼개지 않는다', () {
      final r = parse(['홍길동', '수석연구원 Ph.D', '(주)한빛', '010-1234-5678']);
      expect(r.title, contains('Ph.D'));
    });
  });

  group('벌어진 끝 음절을 붙인다', () {
    test('`운영 팀` → `운영팀`', () {
      final r = parse([
        'iTEASY',
        '매니지드운영본부 | 매니지드운영 팀',
        '조종환 팀장',
        '(주)아이티이지',
      ]);
      expect(r.department, '매니지드운영본부 매니지드운영팀');
    });

    test('⚠️ 두 글자 꼬리는 그대로 둔다 — `사업 1팀`은 그렇게 인쇄돼 있다', () {
      final r = parse(['(주)한빛', '대리', '사업 1팀', '홍길동', '010-1234-5678']);
      expect(r.department, '사업 1팀');
    });
  });
}
