/// **두 글자 브랜드는 회사명의 일부다**(2026-08-29, globe2030님 제보).
///
/// ## 무엇이 문제였나
///
/// 회사명 앞의 영문 1~2글자를 **무조건 뗐다.** 그림 로고를 글자로 잘못 읽은
/// 경우(`GO 선호라이팅 (주)`)를 걷어내려던 것인데, **국내 대기업 이름이 통째로
/// 잘렸다.**
///
/// ```
/// GS 스포츠 → 스포츠      SK 텔레콤 → 텔레콤      LG 전자 → 전자
/// GS스포츠  → GS스포츠    (붙여 쓰면 멀쩡했다)
/// ```
///
/// ✅ **실물**: globe2030님 명함에서 회사가 `스포츠`로 저장됐다.
///
/// ## 🚨 그냥 끄면 다른 것이 깨진다 — 재 보고 알았다
///
/// 100장(`ocr_measure_mlkit_v2_2026-08-23.tsv`)으로 재 보니 **끄면 3장이
/// 바뀌는데 하나가 나빠졌다** — `SK SK 텔레콤`처럼 **로고와 회사명이 둘 다
/// 같은** 줄에서 기존 규칙이 **중복을 걷어내고** 있었다.
///
/// ⚠️ 이 저장소는 예전에도 여기서 물렸다 — 로고 접두를 떼는 쪽으로 바꿨다가
/// **회사 정확도 64% → 60%**로 떨어뜨린 적이 있다.
///
/// ## 그래서 셋으로 갈랐다
///
/// ```
/// 한 글자                    → 뗀다   (O 알로이스 — 로고 오인식)
/// 앞 글자가 뒤에서 되풀이     → 뗀다   (SK SK 텔레콤)
/// 회사 접미사가 있고 이름이 남음 → 뗀다   (GO 선호라이팅 (주))
/// 그 밖의 두 글자            → 둔다   (GS 스포츠 · SK 텔레콤)
/// ```
///
/// ✅ 최종 측정: **100장 중 2장만 바뀌고 나빠진 것은 없다.**
library;

import 'package:connection_trace_ai_flutter/core/services/ocr_scanner_service.dart';
import 'package:flutter_test/flutter_test.dart';

String company(String line) => OcrScannerService.parseLinesForTesting([
  '홍길동',
  line,
  '010-0000-0000',
]).company;

void main() {
  // 🚨 **2026-08-30(추가 614): 값에서 띄어쓰기가 사라졌다. 취지는 그대로다.**
  //
  // 이 검사가 지키는 것은 *"`GS` 를 자르지 않는다"* 이고 **그것은 안 바뀌었다.**
  // 바뀐 것은 **`GS 스포츠` 를 `GS스포츠` 로 붙인다**는 것뿐이다.
  //
  // 📌 **근거는 정답지다** — 190장 정답지가 이 둘을 **붙여** 적고 있다.
  //
  // ```
  // IMG_4239   기기 「SK 텔레콤」   정답 「SK텔레콤」
  // card2      기기 「GS 스포츠」   정답 「GS스포츠」
  // ```
  //
  // ⚠️ **자른 것이 아니라 붙인 것이다.** 「스포츠」로 잘리던 제보 상황은 여전히
  //    막혀 있다 — 아래 값이 `스포츠` 가 되면 그때가 회귀다.
  group('⭐ 두 글자 브랜드는 남긴다 — 실물 제보', () {
    test('GS 스포츠', () => expect(company('GS 스포츠'), 'GS스포츠'));
    test('SK 텔레콤', () => expect(company('SK 텔레콤'), 'SK텔레콤'));
    test('LG 전자', () => expect(company('LG 전자'), 'LG전자'));
    test('DB 손해보험', () => expect(company('DB 손해보험'), 'DB손해보험'));
    test('붙여 쓴 것은 원래 멀쩡했다', () => expect(company('GS스포츠'), 'GS스포츠'));
  });

  group('🚨 그래도 떼야 하는 셋', () {
    test('한 글자는 로고 오인식으로 본다', () {
      expect(company('O 알로이스'), '알로이스');
    });

    test('로고와 회사명이 같으면 중복을 걷어낸다 — 100장 측정에서 나온 사례', () {
      // 중복을 걷어내는 것은 그대로이고, 남은 값의 띄어쓰기만 붙는다(위 참조).
      expect(company('SK SK 텔레콤'), 'SK텔레콤');
    });

    test('회사 접미사가 있고 이름이 남으면 앞 글자는 로고다(추가 318)', () {
      expect(company('GO 선호라이팅 (주)'), '선호라이팅 (주)');
    });
  });

  group('⚠️ 접미사밖에 없으면 앞 글자가 회사명이다', () {
    test('SK 주식회사 — 떼면 「주식회사」만 남아 뜻이 없다', () {
      expect(company('SK 주식회사'), 'SK 주식회사');
    });
  });
}
