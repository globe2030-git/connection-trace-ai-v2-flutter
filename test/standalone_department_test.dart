// 한 줄로 따로 인쇄된 **부서**를 부서 칸에 넣는 규칙(2026-08-29).
//
// ## ⚠️ 이것은 2026-08-19에 닫아 둔 문을 여는 것이다
//
// 추가 321은 *"부서를 새로 찾아 나서지 않는다 — 회사명 자리를 뺏는다"*고
// 정했다. 그러면서 *"가르면 직함 칸이 비는데 그것이 이득인지 손해인지 아직
// 안 쟀다. **재고 나서 넓힌다**"*고 길을 열어 뒀다.
//
// **쟀다.** 사람이 전사한 정답 101장 대비:
//
// ```
// 부서 정답 일치  40 → 48장     (회사·직함·이름은 21·63·73으로 그대로)
// ```
//
// 회사 칸을 뺏지 않았다 — 아래 검사들이 그 조건을 하나씩 잠근다.
//
// 🚨 **조건이 규칙의 절반이다.** 정답 대비로 깨진 장이 실제로 나왔고
// (`주식회사 디엠지그룹`이 「그룹」으로 끝나 부서로 끌려왔다), 그래서 법인
// 표기 검사가 붙었다. 조건을 지우면 조용히 회사가 부서 칸으로 넘어간다.
import 'package:connection_trace_ai_flutter/core/services/ocr_scanner_service.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  OcrScanResult parse(List<String> lines) =>
      OcrScannerService.parseLinesForTesting(lines);

  group('한 줄로 따로 있는 부서를 집는다', () {
    test('부서만 한 줄이면 부서 칸으로 간다 — 버려지지 않는다', () {
      final r = parse(['홍길동', '대리', 'GS 스포츠', '마케팅팀', '010-1234-5678']);
      expect(r.department, '마케팅팀');
      expect(r.title, '대리');
      expect(r.company, contains('GS'));
    });

    test('🚨 직함이 비어 있으면 이 규칙은 **안 돈다** — 아직 못 고치는 자리', () {
      // 명함에 직함이 없고 부서만 있으면, 부서 줄이 **직함 칸의 약한 폴백**으로
      // 먼저 들어가 버려 leftover 에 남지 않는다. 그래서 이 규칙에 닿지 않는다.
      //
      // ⚠️ **고치려다 되물렸다.** 「직함 칸이 통째로 부서 모양이면 부서로
      //    옮긴다」를 붙여 정답 101장으로 재 봤더니 **부서는 48장 그대로**이고
      //    직함이 63 → 64장으로 한 장 늘 뿐이었다. 2026-08-19에 사용자가 정한
      //    경계(추가 321 「부서를 새로 찾아 나서지 않는다」)를 더 넘을 근거로는
      //    **한 장은 얇다.** 그래서 지금 상태를 그대로 적어 둔다.
      //
      // 📌 이 검사는 「이래야 한다」가 아니라 **「지금 이렇다」**를 적은 것이다.
      //    나중에 더 재서 넓히면 이 기대가 먼저 깨질 것이고, 그게 신호다.
      final r = parse(['홍길동', 'GS 스포츠', '마케팅팀', '010-1234-5678']);
      expect(r.department, isEmpty);
      expect(r.title, '마케팅팀');
    });

    test('부서 접미사 여럿을 본다', () {
      // ⚠️ 줄 순서를 **실제 명함 배치**(이름 → 회사 → 부서)로 둔다. 부서 줄이
      //    이름보다 앞에 오면 **이름 뽑기**가 그것을 이름으로 집는데, 그건 이
      //    규칙 밖의 오래된 약점이라 여기서 다루지 않는다. 직함 줄도 넣는다 —
      //    없으면 부서가 직함 칸으로 가 버린다(바로 위 검사).
      for (final d in ['전산부', '커뮤니케이션팀', 'ICT사업부문', '여행보험팀']) {
        final r = parse(['김철수', '과장', '(주)한빛정보기술', d, '010-1111-2222']);
        expect(r.department, d, reason: d);
      }
    });

    test('이미 부서를 찾았으면 덮지 않는다', () {
      final r = parse(['(주)한빛정보기술', '디지털 커뮤니케이션 파트 / 책임', '영업팀']);
      expect(r.department, contains('디지털'));
    });
  });

  group('⚠️ 손대지 않는 줄 — 이 조건들이 규칙의 절반이다', () {
    test('법인 표기가 붙으면 회사다 — 「그룹」으로 끝나도 부서가 아니다', () {
      // 정답 대비 실측에서 실제로 깨진 장이다.
      final r = parse(['주식회사 디엠지그룹', '홍길동', '010-1234-5678']);
      expect(r.department, isNot(contains('디엠지')));
      expect(r.company, contains('디엠지그룹'));
    });

    test('정부 부처는 부서가 아니다 — 인증 배지다', () {
      // `③산업통상자원부`·`G 중소벤처기업부`가 부서 칸에 들어왔다(실측).
      final r = parse(['(주)한빛정보기술', '홍길동', '중소벤처기업부', '010-1234-5678']);
      expect(r.department, isNot(contains('중소벤처기업부')));
    });

    test('🚨 그런데 부처가 **회사**인 명함이 있다 — 공무원 명함', () {
      // `IMG_4250` 실물: 로고 옆 「통일부」가 회사, 「정책기획과 / 주무관」이
      // 부서·직함이다. 부서 칸에서 거르되 **회사 후보로는 살아 있어야** 한다.
      final r = parse(['통일부', '정책기획과', '주무관', '홍길동']);
      expect(r.company, '통일부');
      expect(r.department, '정책기획과');
    });

    test('글머리 기호로 시작하면 인증 배지다', () {
      final r = parse(['(주)한빛정보기술', '홍길동', '•산업통상자원부', '010-1234-5678']);
      expect(r.department, isEmpty);
    });

    test('회사로 고른 줄을 부서로 가져오지 않는다', () {
      // `무지개청소년 센터`처럼 회사면서 「센터」로 끝나는 이름이 있다.
      final r = parse(['무지개청소년 센터', '홍길동', '010-1234-5678']);
      expect(r.company, contains('센터'));
      expect(r.department, isEmpty);
    });

    test('직함 낱말이 든 줄은 부서로 쓰지 않는다', () {
      final r = parse(['(주)한빛정보기술', '홍길동', '영업본부장', '010-1234-5678']);
      expect(r.department, isEmpty);
      expect(r.title, contains('본부장'));
    });
  });

  group('쉼표로 끊긴 순수 영문 줄은 슬로건이지 직함이 아니다', () {
    test('오독된 슬로건이 직함 칸에 남지 않는다', () {
      final r = parse(['GS 스포츠', 'Soulor deoud, FC SEDUL', '홍길동', '010-1234-5678']);
      expect(r.title, isNot(contains('SEDUL')));
    });

    test('⚠️ 쉼표 없는 정상 영문 직함은 그대로 둔다 — 되물린 자리', () {
      // 처음에는 「순수 영문에 직함 낱말이 없으면 버린다」로 잡았다가
      // `Business Development`가 지워져 되물렸다.
      expect(
        parse(['(주)한빛정보기술', 'John Smith', 'Business Development']).title,
        'Business Development',
      );
    });
  });
}
