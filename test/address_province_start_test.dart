// **시·도 이름으로 시작하는 조직명이 주소로 잡히던 것**을 고친다(2026-08-30).
//
// ## 어떻게 찾았나 — 어제는 세 번 물렸다
//
// [추가 605]에 *"원인 자리를 못 찾았다"*고 적고 실패한 접근 셋을 남겼다.
// 오늘은 **코드에 임시 자국(디버그 출력)을 남겨** 그 줄이 어느 경로로 주소가
// 되는지부터 봤다. **어제 스스로 적어 둔 처방이다** —
// *"먼저 볼 것은 「그 줄이 어느 경로로 주소가 되는가」이지 정규식이 아니다."*
//
// ## 원인 — 두 겹이었다
//
// ```
// 서울컨벤션뷰로                       ← 「서울」로 시작 + 「로」로 끝 → 주소로 인식
// 서울관광재단 03190, 서울특별시 …      ← 「서울」관광재단에서 매칭이 시작
// ```
//
// 둘 다 **조직 이름인데 주소로 잡혔다.** 그 줄이 주소 칸을 차지하면 진짜 주소는
// 갈 곳이 없어 **「5층」이 있다는 이유로 상세주소에 통째로** 들어간다.
// **한 줄 때문에 주소·상세주소·우편번호 세 칸이 함께 틀렸다.**
//
// ## 가르는 근거 둘
//
// ```
// ① 시·도 뒤에 오는 것   진짜 주소는 공백·숫자가 오거나 특별시·광역시·도·시·군·구
//                       「서울관광재단」의 「관」은 그중 어느 것도 아니다
// ② 숫자가 있는가        진짜 주소에는 건물번호나 우편번호가 있다
//                       「서울컨벤션뷰로」에는 없다
// ```
//
// ⚠️ **①만으로는 부족했다** — 자국을 남겨 보니 `서울컨벤션뷰로`가 먼저 주소를
// 차지하고 있었다. **둘 다 있어야 두 겹이 다 풀린다.**
//
// ## 잰 것 — 기기 원문 96장
//
// ```
// 주소     83% → 85%     일치 67 → 69
// 상세주소  76% → 79%     일치 61 → 63
// 회사 61% · 부서 78% · 직함 67% · 이름 85%  그대로
// ```
//
// 🚨 **우편번호가 88% → 83%로 「떨어졌는데」 파서가 나빠진 것이 아니다.**
// 오검출로 세어진 여섯이 **명함에 실제로 인쇄된 우편번호**다(`card_129`의
// `08808`은 사진으로 확인했다). **정답지 쪽이 비어 있다.** 고치면 올라간다.
import 'package:connection_trace_ai_flutter/core/services/ocr_scanner_service.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  OcrScanResult parse(List<String> lines) =>
      OcrScannerService.parseLinesForTesting(lines);

  test('부서 이름이 주소로 잡히지 않는다 — `서울컨벤션뷰로`', () {
    final r = parse([
      '서울컨벤션뷰로',
      'MICE지원팀 | 주임',
      '이현아',
      '서울관광재단 03190, 서울특별시 종로구 청계천로 85, 5층',
    ]);
    expect(r.address, isNot(contains('뷰로')));
    expect(r.addressDetail, isNot(contains('청계천로')));
  });

  test('회사명이 주소로 잡히지 않는다 — `서울관광재단`', () {
    final r = parse([
      '홍길동',
      '주임',
      '서울관광재단 03190, 서울특별시 종로구 청계천로 85, 5층',
    ]);
    expect(r.address, isNot(contains('관광재단')));
    expect(r.address, contains('청계천로'));
    expect(r.postalCode, '03190');
  });

  group('⚠️ 손대지 않는 줄 — 이 조건들이 규칙의 절반이다', () {
    test('진짜 시·도로 시작하는 주소는 그대로', () {
      final r = parse(['홍길동', '서울특별시 강남구 테헤란로 110, 5층', '(주)한빛']);
      expect(r.address, contains('테헤란로'));
      expect(r.addressDetail, '5층');
    });

    test('`경기도`처럼 도 이름이 붙은 것도 그대로', () {
      final r = parse(['홍길동', '경기도 성남시 분당구 판교로 255, 3층', '(주)한빛']);
      expect(r.address, contains('판교로'));
    });

    test('시·군·구부터 시작하는 주소도 그대로 — 도/시가 생략된 명함', () {
      final r = parse(['홍길동', '강남구 테헤란로 123, 7층', '(주)한빛']);
      expect(r.address, contains('테헤란로'));
    });
  });
}
