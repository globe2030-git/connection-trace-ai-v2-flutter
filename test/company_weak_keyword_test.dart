// **약한 회사 낱말만 있는 줄은, 같은 명함에 법인 표기가 있으면 회사가 아니다**
// (2026-08-30).
//
// ## 증상 — 회사 칸에 부서가 들어간다
//
// ```
// 기업부설연구소               →  회사 칸   (정답 (주)그린아이티코리아)
// MNO마케팅그룹 로밍마케팅팀     →  회사 칸   (정답 SK텔레콤)
// Production Support Group   →  회사 칸   (정답 현대제철주식회사)
// ```
//
// ## 원인 — 같은 낱말로 회사도 끝나고 부서도 끝난다
//
// `연구소`·`그룹`·`센터` 는 **회사 키워드**다(`무지개청소년센터` 는 진짜
// 회사명이다). 그런데 **부서 이름도 같은 낱말로 끝난다.** 낱말만 보고는 못
// 가른다.
//
// 📌 **가르는 근거는 「같은 명함에 더 강한 표기가 있는가」다** — `(주)`·
// `주식회사`·`Inc.` 는 **회사에만** 붙는다. 그런 줄이 따로 있으면 약한 낱말
// 줄은 부서 쪽이다.
//
// ⚠️ **더 강한 줄이 없으면 예전 그대로 회사로 본다** — 법인 표기 없이
// `…센터` 로만 된 회사가 실제로 있다.
//
// ## 잰 것 — 기기 원문 96장
//
// ```
// 회사 64% → 67%     부서 75% → 78%     전체 82% → 83%
// 이름 85% · 직함 67% 그대로
// ```
//
// 부서가 함께 오른 것은 **회사가 가져가던 줄이 부서 쪽으로 왔기 때문**이다.
import 'package:connection_trace_ai_flutter/core/services/ocr_scanner_service.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  OcrScanResult parse(List<String> lines) =>
      OcrScannerService.parseLinesForTesting(lines);

  test('법인 표기가 있으면 약한 낱말 줄은 부서다 — card_28', () {
    final r = parse([
      '기업부설연구소',
      '김효성 연구소장',
      '(주)그린아이티코리아',
      '010-1234-5678',
    ]);
    expect(r.company, '(주)그린아이티코리아');
    expect(r.department, '기업부설연구소');
  });

  test('영문 조직 단위도 같다 — card_05', () {
    final r = parse([
      '양국석 Kuk-Seok Yang',
      '상무 / 생산지원실장',
      'Production Support Group',
      '현대제철주식회사',
      '010-1234-5678',
    ]);
    expect(r.company, '현대제철주식회사');
  });

  group('⚠️ 더 강한 줄이 없으면 예전 그대로', () {
    test('법인 표기 없이 `…센터` 로만 된 회사는 그대로 회사다', () {
      final r = parse(['무지개청소년 센터', '홍길동', '대리', '010-1234-5678']);
      expect(r.company, contains('센터'));
    });

    test('`삼성그룹` 도 그대로', () {
      final r = parse(['홍길동', '대리', '삼성그룹', '010-1234-5678']);
      expect(r.company, '삼성그룹');
    });
  });

  test('줄 앞의 로고 조각을 뗀다 — 오늘 뺐다가 다시 넣은 규칙', () {
    // 처음엔 숫자가 안 움직여 뺐는데(추가 599), 회사 고르기를 고치자
    // 그 줄이 비로소 부서 후보까지 와서 효과가 생겼다.
    // 📌 **조건이 바뀌면 다시 잰다.**
    final r = parse([
      '0 기업부설연구소',
      '김효성 연구소장',
      '(주)그린아이티코리아',
      '010-1234-5678',
    ]);
    expect(r.department, '기업부설연구소');
  });
}
